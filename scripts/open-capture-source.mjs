import fs from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const puppeteer = require('puppeteer-core');
const root = fileURLToPath(new URL('../', import.meta.url));
const output = 'D:/workspace/MarkMoney/output/devsnapkit/text-hero-redesign-2026-10-30';
await fs.mkdir(output, { recursive: true });
const html = await fs.readFile(path.join(root, 'tests/fixtures/text-demo-source.html'));
const server = http.createServer((request, response) => { response.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' }); response.end(html); });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const url = `http://127.0.0.1:${server.address().port}/capture-source`;
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, defaultViewport: null, args: ['--start-maximized', '--no-proxy-server', '--no-first-run'] });
const page = (await browser.pages())[0];
await page.goto(url, { waitUntil: 'networkidle0' });
const client = await page.createCDPSession();
const window = await client.send('Browser.getWindowForTarget');
await client.send('Browser.setWindowBounds', { windowId: window.windowId, bounds: { windowState: 'normal' } });
await client.send('Browser.setWindowBounds', { windowId: window.windowId, bounds: { windowState: 'maximized' } });
await page.bringToFront();
await client.detach();
const bounds = await page.$eval('.capture-board', node => node.getBoundingClientRect().toJSON());
await fs.writeFile(path.join(output, 'source-session.json'), JSON.stringify({ url, bounds, viewport: await page.evaluate(() => ({ width: innerWidth, height: innerHeight, outerWidth, outerHeight, screenX, screenY, devicePixelRatio })) }, null, 2));
console.log(JSON.stringify({ ready: true, url, bounds, output }));
process.stdin.setEncoding('utf8');
await new Promise(resolve => { process.stdin.on('data', text => { if (text.includes('stop')) resolve(); }); process.once('SIGINT', resolve); });
await browser.close();
await new Promise(resolve => server.close(resolve));
