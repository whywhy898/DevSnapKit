// Generates the indexable /terms/ and /privacy/ pages from src/legal/legalContent.json,
// the same file the editor's legal modals render. Run by `npm run build`; output is committed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://devsnapkit.com';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function renderBody(body) {
  return body.map((seg) => {
    if (seg.code) return `<code>${esc(seg.code)}</code>`;
    if (seg.email) return `<a href="mailto:${esc(seg.email)}">${esc(seg.email)}</a>`;
    return esc(seg.text ?? '');
  }).join('');
}

export function loadLegalContent() {
  return JSON.parse(fs.readFileSync(path.join(root, 'src/legal/legalContent.json'), 'utf8'));
}

export function renderLegalPage(doc, other) {
  const url = `${SITE}/${doc.slug}/`;
  const title = `${doc.title} | DevSnapKit`;
  const callout = doc.callout ? `\n      <aside class="legal-callout"><p><strong>${esc(doc.callout.label)}</strong> ${esc(doc.callout.text)}</p></aside>` : '';
  const sections = doc.sections.map((s) => `\n      <h2>${esc(s.heading)}</h2>\n      <p>${renderBody(s.body)}</p>`).join('');
  return `<!doctype html>
<!-- Generated by scripts/build-legal-pages.mjs from src/legal/legalContent.json. Do not edit by hand. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(doc.description)}">
  <link rel="canonical" href="${url}">
  <link rel="icon" type="image/svg+xml" href="/favicon.svg">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="DevSnapKit">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(doc.description)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${SITE}/og-image.png">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${esc(title)}">
  <meta name="twitter:description" content="${esc(doc.description)}">
  <meta name="twitter:image" content="${SITE}/og-image.png">
  <link rel="preload" href="/seo/manrope-latin.woff2" as="font" type="font/woff2" crossorigin>
  <script>try{const t=localStorage.getItem('devsnapkit_landing_theme');if(t==='light'||t==='dark')document.documentElement.dataset.theme=t}catch{}</script>
  <link rel="stylesheet" href="/seo/landing.css">
  <link rel="stylesheet" href="/seo/legal.css">
  <script src="/seo/landing.js" defer></script>
</head>
<body class="legal-page" data-studio-cta="/?editor=1" data-studio-cta-label="Open the Studio">
  <a class="skip-link" href="#main">Skip to content</a>
  <header class="site-header wrap">
    <a class="brand" href="/" aria-label="DevSnapKit home"><img src="/favicon.svg" alt="" width="30" height="30">DevSnap<span>Kit</span><small>STUDIO</small></a>
    <nav aria-label="Main navigation"><a href="/">Home</a><a href="/${other.slug}/">${esc(other.title)}</a><button class="theme-toggle" type="button" aria-label="Switch color theme">Theme</button></nav>
  </header>
  <main id="main">
    <article class="legal-doc wrap" aria-labelledby="legal-title">
      <p class="eyebrow">LEGAL</p>
      <h1 id="legal-title">${esc(doc.title)}</h1>
      <p class="legal-date">${esc(doc.date)}</p>${callout}${sections}
      <p class="legal-related">See also: <a href="/${other.slug}/">${esc(other.title)}</a> · <a href="mailto:support@devsnapkit.com">support@devsnapkit.com</a></p>
    </article>
  </main>
  <nav class="tools-nav wrap" aria-label="Screenshot tools"><a href="/screenshot-beautifier/">Screenshot beautifier</a><a href="/og-image-generator/">OG image generator</a><a href="/product-hunt-image-maker/">Product Hunt image maker</a><a href="/add-text-to-image/">Add text to image</a></nav>
  <footer class="site-footer wrap"><a class="brand" href="/"><img src="/favicon.svg" alt="" width="24" height="24">DevSnap<span>Kit</span></a><p>Screenshot mockups, right in your browser.</p><div><a href="/">Home</a><a href="/?editor=1">Open studio ↗</a><a href="/terms/">Terms of Service</a><a href="/privacy/">Privacy Policy</a><a href="mailto:support@devsnapkit.com">Contact</a></div></footer>
</body>
</html>
`;
}

export function renderLegalPages() {
  const { terms, privacy } = loadLegalContent();
  return {
    'public/terms/index.html': renderLegalPage(terms, privacy),
    'public/privacy/index.html': renderLegalPage(privacy, terms),
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  for (const [rel, html] of Object.entries(renderLegalPages())) {
    const file = path.join(root, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, html);
    console.log('legal page:', rel);
  }
}
